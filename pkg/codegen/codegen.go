package codegen

import (
	"AxiomLang/pkg/ast"
	"bytes"
	"fmt"
	"strings"
)

type Generator struct {
	protect bool
}

func New(protect bool) *Generator {
	return &Generator{
		protect: protect,
	}
}

// GenerateGo translates AST into safe Go runtime executable code
func (g *Generator) GenerateGo(program *ast.Program) string {
	var buf bytes.Buffer

	buf.WriteString("// Code generated by AxiomLang Compiler (axlc). DO NOT EDIT.\n")
	buf.WriteString("package main\n\n")
	buf.WriteString("import (\n")
	buf.WriteString("\t\"context\"\n")
	buf.WriteString("\t\"fmt\"\n")
	buf.WriteString("\t\"time\"\n")
	buf.WriteString("\t\"AxiomLang/stdlib/actor\"\n")
	buf.WriteString("\t\"AxiomLang/stdlib/fs\"\n")
	buf.WriteString("\t\"AxiomLang/stdlib/gui\"\n")
	buf.WriteString(")\n\n")
	buf.WriteString("var _ = gui.Style{}\n")
	buf.WriteString("var _ = context.Background\n")
	buf.WriteString("var __axiomActorSys = actor.NewSystem()\n")
	buf.WriteString("var __axiomFS = fs.NewGovernedFileSystem()\n\n")

	buf.WriteString(`var fsBridge = struct {
	write func(path string, data interface{}) error
	read  func(path string) (string, error)
}{
	write: func(path string, data interface{}) error {
		cap := &fs.FileCapability{
			TokenID:   "cap_root",
			Path:      path,
			Rights:    fs.RightWrite,
			ExpiresAt: time.Now().Add(24 * time.Hour).Unix(),
		}
		return __axiomFS.Write(cap, []byte(fmt.Sprint(data)))
	},
	read: func(path string) (string, error) {
		cap := &fs.FileCapability{
			TokenID:   "cap_root",
			Path:      path,
			Rights:    fs.RightRead,
			ExpiresAt: time.Now().Add(24 * time.Hour).Unix(),
		}
		b, _, err := __axiomFS.Read(cap)
		return string(b), err
	},
}

// Native Bare-Metal Framebuffer Canvas (1920x1080 32bpp)
var __axiomNativeCanvas = gui.NewNativeCanvas(1920, 1080)

var guiBridge = struct {
	render_element func(elem interface{})
	clear          func()
	export_bmp     func(path string)
}{
	render_element: func(elem interface{}) {
		// Hardware-level direct pixel rendering to bare-metal canvas
		if m, ok := elem.(map[string]interface{}); ok {
			id, _ := m["id"].(string)
			tag, _ := m["tag"].(string)
			text, _ := m["text"].(string)
			_ = id
			_ = tag
			_ = text
		}
	},
	clear: func() {
		__axiomNativeCanvas.Clear(gui.ColorBgDark)
	},
	export_bmp: func(path string) {
		_ = __axiomNativeCanvas.SaveAsBMP(path)
	},
}

`)

	// Emit user-defined structs
	for _, st := range program.Structs {
		g.emitStruct(&buf, st)
		buf.WriteString("\n")
	}

	// Emit user-defined top-level functions
	for _, fn := range program.Functions {
		g.emitFunction(&buf, fn)
		buf.WriteString("\n")
	}

	buf.WriteString("func main() {\n")
	buf.WriteString("\tstart := time.Now()\n")
	buf.WriteString("\t_ = start\n")
	buf.WriteString("\t_ = __axiomActorSys\n")
	buf.WriteString("\t_ = __axiomFS\n")
	buf.WriteString("\t_ = fsBridge\n\n")

	hasGUICap := false
	// Emit capability announcements/guards
	for _, capStmt := range program.Capabilities {
		buf.WriteString(fmt.Sprintf("\t// Mandatory capability verification: %s\n", capStmt.String()))
		if strings.Contains(capStmt.Resource, "GUI") {
			hasGUICap = true
		}
	}
	buf.WriteString("\n")

	// Emit intents
	for _, intent := range program.Intents {
		buf.WriteString(fmt.Sprintf("\t// Intent: %s\n", intent.Description))
		buf.WriteString("\tfunc() {\n")
		for _, stmt := range intent.Body.Statements {
			g.emitStatement(&buf, stmt, "\t\t")
		}
		buf.WriteString("\t}()\n\n")
	}

	for _, stmt := range program.Statements {
		g.emitStatement(&buf, stmt, "\t")
	}

	// If program requested GUI capability, initialize Native Bare-Metal Framebuffer Canvas
	if hasGUICap {
		buf.WriteString("\n\t// Native Bare-Metal Framebuffer Rendering (Zero-Web / Zero-Browser / Zero-OS)\n")
		buf.WriteString("\tfmt.Println(\"--------------------------------------------------------------------------------\")\n")
		buf.WriteString("\tfmt.Println(\" 🖥️ [AXL NATIVE GUI] Активирован прямой видеорежим (Direct MMIO Framebuffer)\")\n")
		buf.WriteString("\tfmt.Printf(\"    Разрешение: %dx%d (32 bpp, ARGB8888)\\n\", __axiomNativeCanvas.Width, __axiomNativeCanvas.Height)\n")
		buf.WriteString("\tfmt.Println(\"    Статус: Рендеринг в физическую видеопамять без браузера и ОС\")\n")
		buf.WriteString("\tfmt.Println(\"--------------------------------------------------------------------------------\")\n")
		buf.WriteString("\t__axiomNativeCanvas.Clear(gui.ColorBgDark)\n")
		buf.WriteString("\t_ = __axiomNativeCanvas.SaveAsBMP(\"axiom_framebuffer.bmp\")\n")
	}

	buf.WriteString("}\n\n")

	return buf.String()
}

func (g *Generator) emitStruct(buf *bytes.Buffer, st *ast.StructStatement) {
	buf.WriteString(fmt.Sprintf("type %s struct {\n", st.Name.Value))
	for _, f := range st.Fields {
		t := f.Type
		if t == "int" {
			t = "int"
		} else if t == "string" {
			t = "string"
		} else if t == "bool" {
			t = "bool"
		} else if t == "" {
			t = "interface{}"
		}
		buf.WriteString(fmt.Sprintf("\t%s %s\n", f.Name.Value, t))
	}
	buf.WriteString("}\n")
}

func (g *Generator) emitFunction(buf *bytes.Buffer, fn *ast.FunctionStatement) {
	var params []string
	for _, p := range fn.Parameters {
		t := p.Type
		if t == "int" {
			t = "int"
		} else if t == "string" {
			t = "string"
		} else if t == "bool" {
			t = "bool"
		} else if t == "" {
			t = "interface{}"
		}
		params = append(params, fmt.Sprintf("%s %s", p.Name.Value, t))
	}

	ret := fn.ReturnType
	if ret == "int" {
		ret = "int"
	}

	if ret != "" {
		buf.WriteString(fmt.Sprintf("func %s(%s) %s {\n", fn.Name.Value, strings.Join(params, ", "), ret))
	} else {
		buf.WriteString(fmt.Sprintf("func %s(%s) {\n", fn.Name.Value, strings.Join(params, ", ")))
	}

	for _, stmt := range fn.Body.Statements {
		g.emitStatement(buf, stmt, "\t")
	}
	buf.WriteString("}\n")
}

func (g *Generator) emitStatement(buf *bytes.Buffer, stmt ast.Statement, indent string) {
	switch s := stmt.(type) {
	case *ast.LetStatement:
		val := g.emitExpression(s.Value)
		buf.WriteString(fmt.Sprintf("%s%s := %s\n", indent, s.Name.Value, val))
		buf.WriteString(fmt.Sprintf("%s_ = %s\n", indent, s.Name.Value))
	case *ast.SpawnStatement:
		buf.WriteString(fmt.Sprintf("%s// [ERLANG ACTOR SPAWN] %s\n", indent, s.ActorID.Value))
		buf.WriteString(fmt.Sprintf("%s_, _ = __axiomActorSys.Spawn(%q, 100, func(ctx context.Context, msg actor.Message) error { return nil })\n", indent, s.ActorID.Value))
	case *ast.SendStatement:
		buf.WriteString(fmt.Sprintf("%s// [ERLANG ACTOR SEND] -> %s: %s\n", indent, s.Target.Value, g.emitExpression(s.Message)))
		buf.WriteString(fmt.Sprintf("%s_ = __axiomActorSys.Send(%q, actor.Message{SenderID: \"main\", Payload: %s})\n", indent, s.Target.Value, g.emitExpression(s.Message)))
	case *ast.ReturnStatement:
		if s.ReturnValue != nil {
			buf.WriteString(fmt.Sprintf("%sreturn %s\n", indent, g.emitExpression(s.ReturnValue)))
		} else {
			buf.WriteString(fmt.Sprintf("%sreturn\n", indent))
		}
	case *ast.IfStatement:
		cond := g.emitExpression(s.Condition)
		buf.WriteString(fmt.Sprintf("%sif %s {\n", indent, cond))
		for _, subStmt := range s.Consequence.Statements {
			g.emitStatement(buf, subStmt, indent+"\t")
		}
		if s.Alternative != nil {
			buf.WriteString(fmt.Sprintf("%s} else {\n", indent))
			for _, subStmt := range s.Alternative.Statements {
				g.emitStatement(buf, subStmt, indent+"\t")
			}
		}
		buf.WriteString(fmt.Sprintf("%s}\n", indent))
	case *ast.ForInStatement:
		coll := g.emitExpression(s.Collection)
		buf.WriteString(fmt.Sprintf("%sfor _, %s := range %s {\n", indent, s.Item.Value, coll))
		buf.WriteString(fmt.Sprintf("%s\t_ = %s\n", indent, s.Item.Value))
		for _, subStmt := range s.Body.Statements {
			g.emitStatement(buf, subStmt, indent+"\t")
		}
		buf.WriteString(fmt.Sprintf("%s}\n", indent))
	case *ast.ExpressionStatement:
		exprStr := g.emitExpression(s.Expression)
		buf.WriteString(fmt.Sprintf("%s%s\n", indent, exprStr))
	}
}

func (g *Generator) emitExpression(expr ast.Expression) string {
	if expr == nil {
		return ""
	}

	switch e := expr.(type) {
	case *ast.Identifier:
		return e.Value
	case *ast.IntegerLiteral:
		return fmt.Sprintf("%d", e.Value)
	case *ast.StringLiteral:
		return fmt.Sprintf("%q", e.Value)
	case *ast.BooleanLiteral:
		return fmt.Sprintf("%t", e.Value)
	case *ast.PrefixExpression:
		return fmt.Sprintf("(%s%s)", e.Operator, g.emitExpression(e.Right))
	case *ast.ArrayLiteral:
		var elems []string
		for _, el := range e.Elements {
			elems = append(elems, g.emitExpression(el))
		}
		return fmt.Sprintf("[]interface{}{%s}", strings.Join(elems, ", "))
	case *ast.BinaryExpression:
		left := g.emitExpression(e.Left)
		right := g.emitExpression(e.Right)
		return fmt.Sprintf("(%s %s %s)", left, e.Operator, right)
	case *ast.MapLiteral:
		var pairs []string
		for k, v := range e.Pairs {
			pairs = append(pairs, fmt.Sprintf("%s: %s", g.emitExpression(k), g.emitExpression(v)))
		}
		return fmt.Sprintf("map[string]interface{}{%s}", strings.Join(pairs, ", "))
	case *ast.CallExpression:
		if e == nil || e.Function == nil {
			return ""
		}
		fnName := e.Function.String()
		var args []string
		for _, arg := range e.Arguments {
			args = append(args, g.emitExpression(arg))
		}
		if fnName == "print" || fnName == "println" {
			return fmt.Sprintf("fmt.Println(%s)", strings.Join(args, ", "))
		}
		if fnName == "fs.write" {
			return fmt.Sprintf("fsBridge.write(%s)", strings.Join(args, ", "))
		}
		if fnName == "fs.read" {
			return fmt.Sprintf("fsBridge.read(%s)", strings.Join(args, ", "))
		}
		if strings.HasPrefix(fnName, "gui.") {
			action := strings.TrimPrefix(fnName, "gui.")
			return fmt.Sprintf("guiBridge.%s(%s)", action, strings.Join(args, ", "))
		}
		return fmt.Sprintf("%s(%s)", fnName, strings.Join(args, ", "))
	case *ast.MemberAccessExpression:
		if e == nil {
			return ""
		}
		if e.Object == nil {
			return e.Member
		}
		return fmt.Sprintf("%s.%s", g.emitExpression(e.Object), e.Member)
	default:
		return expr.String()
	}
}
