# ==============================================================================
# compile_axiom_source() -> %rax (0 = OK, 1 = ERROR)
# ==============================================================================
compile_axiom_source:
    pushq %rbp
    movq %rsp, %rbp
    pushq %rbx
    pushq %r12
    pushq %r13
    pushq %r14
    pushq %r15

    movq $0, dest_pos(%rip)
    movq $0, out_overflow(%rip)
    movq $0, str_count(%rip)
    movq $0, var_count(%rip)
    movq $0, reg_alloc_cnt(%rip)
    movq $0, in_fn_regalloc(%rip)
    movq $0, label_seq(%rip)
    movq $0, has_main_fn(%rip)
    movq $0, struct_fld_cnt(%rip)

    # 1. Initialize Lexer + MCA Parser
    movq source_buffer(%rip), %rdi
    movq source_len(%rip), %rsi
    call parser_init
    testq %rax, %rax
    jnz .L_comp_err

    # 2. Parse into AST
    call parser_parse_program
    testq %rax, %rax
    jz .L_comp_err_destroy
    movq %rax, %r12          # r12 = ast_root

    # 3. Run Static Checker
    movq %r12, %rdi
    call checker_verify_program
    testq %rax, %rax
    jnz .L_comp_err_destroy

    # 4. Emit DWARF .file directive
    movq src_path_ptr(%rip), %rdi
    testq %rdi, %rdi
    jz .L_skip_dwarf_file
    xorq %rsi, %rsi
.L_dlen:
    cmpb $0, (%rdi, %rsi)
    je .L_dlen_done
    incq %rsi
    jmp .L_dlen
.L_dlen_done:
    call dwarf_emit_file

.L_skip_dwarf_file:
    # 5. Emit _start prologue
    leaq code_prologue(%rip), %rsi
    movq $code_prologue_len, %rcx
    call append_to_output

    # 6. Emit top-level statements (and intent { ... } blocks)
    movq AST_OFF_CHILD_PTR(%r12), %rdi
    call codegen_toplevel_stmts

    # 7. If main() exists, call ax_fn_main and exit with %rax, else exit 0
    cmpq $0, has_main_fn(%rip)
    je .L_no_main
    leaq code_call_main(%rip), %rsi
    movq $code_call_main_len, %rcx
    call append_to_output
    jmp .L_emit_fns
.L_no_main:
    leaq code_exit_zero(%rip), %rsi
    movq $code_exit_zero_len, %rcx
    call append_to_output

.L_emit_fns:
    # 8. Emit all user functions (AST_FN)
    movq AST_OFF_CHILD_PTR(%r12), %rdi
    call codegen_all_fns

    # 9. Emit runtime helpers
    leaq code_runtime(%rip), %rsi
    movq $code_runtime_len, %rcx
    call append_to_output

    # 10. Emit .rodata strings
    leaq str_section_header(%rip), %rsi
    movq $str_section_header_len, %rcx
    call append_to_output
    call emit_string_literals

    # 11. HPT Optimization & Invariant Verification
    movq out_asm_buffer(%rip), %rdi
    movq dest_pos(%rip), %rsi
    call hpt_optimize_pipeline
    movq %rax, out_asm_len(%rip)

    movq out_asm_buffer(%rip), %rdi
    movq out_asm_len(%rip), %rsi
    call hpt_verify_flawless_invariants
    testq %rax, %rax
    jz .L_comp_err_destroy

    call parser_destroy

    cmpq $0, out_overflow(%rip)
    jne .L_comp_err

    xorq %rax, %rax
    popq %r15
    popq %r14
    popq %r13
    popq %r12
    popq %rbx
    leave
    ret

.L_comp_err_destroy:
    call parser_destroy
.L_comp_err:
    movq $1, %rax
    popq %r15
    popq %r14
    popq %r13
    popq %r12
    popq %rbx
    leave
    ret

# ==============================================================================
# Pass 1: Top-level statements & intent { ... } blocks, detect fn main
# ==============================================================================
codegen_toplevel_stmts:
    pushq %rbp
    movq %rsp, %rbp
    pushq %r12
    movq %rdi, %r12

.L_cts_loop:
    testq %r12, %r12
    jz .L_cts_done

    movq AST_OFF_TYPE(%r12), %rax
    cmpq $AST_FN, %rax
    je .L_cts_chk_main
    cmpq $AST_INTENT, %rax
    je .L_cts_intent
    cmpq $AST_REQUIRE, %rax
    je .L_cts_next
    cmpq $AST_CAP, %rax
    je .L_cts_cap
    cmpq $AST_ACTOR, %rax
    je .L_cts_next
    cmpq $AST_STRUCT, %rax
    je .L_cts_struct

    movq %r12, %rdi
    call codegen_stmt
    jmp .L_cts_next

.L_cts_cap:
    movq AST_OFF_VAL(%r12), %rax
    testq %rax, %rax
    jz .L_cts_next
    pushq %rax
    leaq insn_cap_max_pre(%rip), %rsi
    movq $insn_cap_max_pre_len, %rcx
    call append_to_output
    popq %rax
    call append_decimal_u64
    leaq insn_cap_max_suf(%rip), %rsi
    movq $insn_cap_max_suf_len, %rcx
    call append_to_output
    jmp .L_cts_next

.L_cts_struct:
    movq AST_OFF_CHILD_PTR(%r12), %rdi
    call register_struct_fields
    jmp .L_cts_next

.L_cts_intent:
    movq AST_OFF_CHILD_PTR(%r12), %rdi
    testq %rdi, %rdi
    jz .L_cts_next
    call codegen_stmt_list
    jmp .L_cts_next

.L_cts_chk_main:
    movq AST_OFF_NAME_PTR(%r12), %rdi
    movq AST_OFF_NAME_LEN(%r12), %rsi
    leaq kw_main_str(%rip), %rdx
    movq $4, %rcx
    call slice_eq
    testq %rax, %rax
    jz .L_cts_next
    movq $1, has_main_fn(%rip)

.L_cts_next:
    movq AST_OFF_NEXT_PTR(%r12), %r12
    jmp .L_cts_loop

.L_cts_done:
    popq %r12
    leave
    ret

