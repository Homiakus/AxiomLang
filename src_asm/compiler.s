    pushq %rbp
    movq %rsp, %rbp
    pushq %r12
    movq %rdi, %r12
.L_caf_loop:
    testq %r12, %r12
    jz .L_caf_done
    cmpq $AST_FN, AST_OFF_TYPE(%r12)
    jne .L_caf_next
    movq %r12, %rdi
    call codegen_fn
.L_caf_next:
    movq AST_OFF_NEXT_PTR(%r12), %r12
    jmp .L_caf_loop
.L_caf_done:
    popq %r12
    leave
    ret

codegen_fn:
    pushq %rbp
    movq %rsp, %rbp
    pushq %r12
    pushq %r13
    pushq %r14
    movq %rdi, %r12

    movq $0, var_count(%rip)
    movq $0, reg_alloc_cnt(%rip)
    movq $1, in_fn_regalloc(%rip)
    movq $0, fn_needs_frame(%rip)
    movq $1, fn_is_leaf(%rip)
    movq $0, tail_call_active(%rip)

    # Emit label: ax_fn_<name>:
    leaq fn_lbl_pre(%rip), %rsi
    movq $fn_lbl_pre_len, %rcx
    call append_to_output
    movq AST_OFF_NAME_PTR(%r12), %rsi
    movq AST_OFF_NAME_LEN(%r12), %rcx
    call append_to_output
    leaq str_def_colon(%rip), %rsi
    movq $str_def_colon_len, %rcx
    call append_to_output

    # Detect if leaf function (no calls/arrays/structs) before allocating regs
    movq AST_OFF_CHILD_PTR(%r12), %rdi
    call fn_check_leaf

    # Pre-allocate parameters (up to 6) and body locals to determine reg_alloc_cnt & frame need
    movq AST_OFF_RIGHT_PTR(%r12), %r13   # param list
    xorq %r14, %r14                      # param idx 0..5
.L_cf_prescan_params:
    testq %r13, %r13
    jz .L_cf_prescan_body
    cmpq $6, %r14
    jge .L_cf_prescan_body
    movq AST_OFF_NAME_PTR(%r13), %rdi
    movq AST_OFF_NAME_LEN(%r13), %rsi
    call var_get_or_alloc
    movq %rax, %rdi
    call var_alloc_reg_if_avail
    incq %r14
    movq AST_OFF_NEXT_PTR(%r13), %r13
    jmp .L_cf_prescan_params

.L_cf_prescan_body:
    movq AST_OFF_CHILD_PTR(%r12), %rdi
    call fn_prescan_stmts
    movq $5, %rax
    cmpq $0, fn_is_leaf(%rip)
    je .L_cf_chk_frame_lim
    movq $9, %rax
.L_cf_chk_frame_lim:
    cmpq %rax, var_count(%rip)
    jle .L_cf_emit_pro
    movq $1, fn_needs_frame(%rip)
.L_cf_emit_pro:
    call emit_fn_prologue

    # Spill parameters from %rdi..%r9 into allocated registers or stack slots
    movq AST_OFF_RIGHT_PTR(%r12), %r13   # param list
    xorq %r14, %r14                      # param idx 0..5
.L_cf_params:
    testq %r13, %r13
    jz .L_cf_body
    cmpq $6, %r14
    jge .L_cf_body

    movq AST_OFF_NAME_PTR(%r13), %rdi
    movq AST_OFF_NAME_LEN(%r13), %rsi
    call var_find
    pushq %rax                           # stack offset

    movq (%rsp), %rdi
    call var_get_reg
    testq %rax, %rax
    jz .L_cfp_stack

    # Emit: movq %<param_reg>, %<var_reg>
    pushq %rax
    leaq insn_mov_only_pre(%rip), %rsi
    movq $insn_mov_only_pre_len, %rcx
    call append_to_output
    leaq param_reg_name_table(%rip), %rbx
    movq %r14, %rcx
    shlq $4, %rcx
    movq (%rbx, %rcx), %rsi
    movq 8(%rbx, %rcx), %rcx
    call append_to_output
    leaq str_comma_sp(%rip), %rsi
    movq $2, %rcx
    call append_to_output
    popq %rax
    call emit_reg_name
    leaq str_def_nl(%rip), %rsi
    movq $1, %rcx
    call append_to_output
    popq %rax
    jmp .L_cfp_next

.L_cfp_stack:
    leaq param_reg_table(%rip), %rbx
    movq %r14, %rcx
    shlq $4, %rcx
    movq (%rbx, %rcx), %rsi
    movq 8(%rbx, %rcx), %rcx
    call append_to_output

    popq %rax
    call append_decimal_u64
    leaq insn_rbp_suf(%rip), %rsi
    movq $insn_rbp_suf_len, %rcx
    call append_to_output

.L_cfp_next:
    incq %r14
    movq AST_OFF_NEXT_PTR(%r13), %r13
    jmp .L_cf_params

.L_cf_body:
    movq AST_OFF_CHILD_PTR(%r12), %rdi
    call codegen_stmt_list

    # Default return 0
    leaq insn_xor_rax(%rip), %rsi
    movq $insn_xor_rax_len, %rcx
    call append_to_output
    call emit_fn_epilogue
    leaq str_def_nl(%rip), %rsi
    movq $1, %rcx
    call append_to_output

    movq $0, in_fn_regalloc(%rip)
    popq %r14
    popq %r13
    popq %r12
    leave
    ret

# ==============================================================================
# codegen_stmt_list / codegen_stmt
# ==============================================================================
codegen_stmt_list:
    pushq %rbp
    movq %rsp, %rbp
    pushq %r12
    movq %rdi, %r12
.L_csl_loop:
    testq %r12, %r12
    jz .L_csl_done
    movq %r12, %rdi
    call codegen_stmt
    movq AST_OFF_NEXT_PTR(%r12), %r12
    jmp .L_csl_loop
.L_csl_done:
    popq %r12
    leave
    ret

codegen_stmt:
    pushq %rbp
    movq %rsp, %rbp
    pushq %r12
    pushq %r13
    pushq %r14
    pushq %r15
    movq %rdi, %r12

    movq AST_OFF_LINE(%r12), %rdi
    call dwarf_emit_loc

    movq AST_OFF_TYPE(%r12), %rax
    cmpq $AST_LET, %rax
    je .L_cs_let
    cmpq $AST_ASSIGN, %rax
    je .L_cs_assign
    cmpq $AST_CALL, %rax
    je .L_cs_call
    cmpq $AST_RETURN, %rax
    je .L_cs_return
    cmpq $AST_IF, %rax
    je .L_cs_if
    cmpq $AST_WHILE, %rax
    je .L_cs_while
    cmpq $AST_FOR, %rax
    je .L_cs_for
    jmp .L_cs_done

.L_cs_let:
    movq AST_OFF_CHILD_PTR(%r12), %rdi
    call codegen_expr
    movq AST_OFF_NAME_PTR(%r12), %rdi
    movq AST_OFF_NAME_LEN(%r12), %rsi
    call var_get_or_alloc
    movq %rax, %r14
    movq %r14, %rdi
    call var_alloc_reg_if_avail
    movq AST_OFF_CHILD_PTR(%r12), %rdi
    call expr_is_str
    testq %rax, %rax
    jz .L_let_store
    movq %r14, %rdi
    call var_mark_str
.L_let_store:
    movq %r14, %rax
    jmp .L_cs_store_var

.L_cs_assign:
    movq AST_OFF_RIGHT_PTR(%r12), %r14
    testq %r14, %r14
    jnz .L_cs_assign_target

    # Fast-path: x = x + imm / x - imm / x + y_reg / x - y_reg when x is in a register
    movq AST_OFF_NAME_PTR(%r12), %rdi
    movq AST_OFF_NAME_LEN(%r12), %rsi
    call var_find
    testq %rax, %rax
    jz .L_csa_normal
    movq %rax, %r13              # dst var offset
    movq %rax, %rdi
    call var_get_reg
    testq %rax, %rax
    jz .L_csa_normal
    movq %rax, %r14              # dst reg 1..5
    movq AST_OFF_NAME_PTR(%r12), %rdi
    movq AST_OFF_NAME_LEN(%r12), %rsi
    call var_check_str
    testq %rax, %rax
    jnz .L_csa_normal

    movq AST_OFF_CHILD_PTR(%r12), %r15
    testq %r15, %r15
    jz .L_csa_normal
    cmpq $AST_EXPR_BIN, AST_OFF_TYPE(%r15)
    jne .L_csa_normal
    movq AST_OFF_VAL(%r15), %rax
    cmpq $TOK_PLUS, %rax
    je .L_csa_op_ok
    cmpq $TOK_MINUS, %rax
    jne .L_csa_normal
.L_csa_op_ok:
    movq AST_OFF_CHILD_PTR(%r15), %rbx
    testq %rbx, %rbx
    jz .L_csa_normal
    cmpq $AST_IDENT, AST_OFF_TYPE(%rbx)
    jne .L_csa_normal
    movq AST_OFF_NAME_PTR(%rbx), %rdi
    movq AST_OFF_NAME_LEN(%rbx), %rsi
    call var_find
    cmpq %r13, %rax
    jne .L_csa_normal

    movq AST_OFF_RIGHT_PTR(%r15), %rbx
    testq %rbx, %rbx
    jz .L_csa_normal
    cmpq $AST_INT, AST_OFF_TYPE(%rbx)
    je .L_csa_imm
    cmpq $AST_IDENT, AST_OFF_TYPE(%rbx)
    jne .L_csa_normal
    movq AST_OFF_NAME_PTR(%rbx), %rdi
    movq AST_OFF_NAME_LEN(%rbx), %rsi
    call var_find
    testq %rax, %rax
    jz .L_csa_normal
    movq %rax, %rdi
    call var_get_reg
    testq %rax, %rax
    jz .L_csa_normal
    pushq %rax                   # src_reg
    cmpq $TOK_PLUS, AST_OFF_VAL(%r15)
    je .L_csa_r_add
    leaq insn_sub_reg_pre(%rip), %rsi
    movq $insn_sub_reg_pre_len, %rcx
    jmp .L_csa_r_emit
.L_csa_r_add:
    leaq insn_add_reg_pre(%rip), %rsi
    movq $insn_add_reg_pre_len, %rcx
.L_csa_r_emit:
    call append_to_output
    popq %rax
    call emit_reg_name
    leaq str_comma_sp(%rip), %rsi
    movq $2, %rcx
    call append_to_output
    movq %r14, %rax
    call emit_reg_name
    leaq str_def_nl(%rip), %rsi
    movq $1, %rcx
    call append_to_output
    jmp .L_cs_done

.L_csa_imm:
    movq AST_OFF_VAL(%rbx), %rax
    cmpq $2147483647, %rax
    ja .L_csa_normal
    pushq %rax
    cmpq $TOK_PLUS, AST_OFF_VAL(%r15)
    je .L_csa_i_add
    leaq insn_sub_imm_pre(%rip), %rsi
    movq $insn_sub_imm_pre_len, %rcx
    jmp .L_csa_i_emit
.L_csa_i_add:
    leaq insn_add_imm_pre(%rip), %rsi
    movq $insn_add_imm_pre_len, %rcx
.L_csa_i_emit:
    call append_to_output
    popq %rax
    call append_decimal_u64
    leaq str_comma_sp(%rip), %rsi
    movq $2, %rcx
    call append_to_output
    movq %r14, %rax
    call emit_reg_name
    leaq str_def_nl(%rip), %rsi
    movq $1, %rcx
    call append_to_output
    jmp .L_cs_done

.L_csa_normal:
    movq AST_OFF_CHILD_PTR(%r12), %rdi
    call codegen_expr
    movq AST_OFF_NAME_PTR(%r12), %rdi
    movq AST_OFF_NAME_LEN(%r12), %rsi
    call var_find
    jmp .L_cs_store_var

.L_cs_assign_target:
    # Evaluate RHS -> push %rax
    movq AST_OFF_CHILD_PTR(%r12), %rdi
    call codegen_expr
    leaq insn_push_rax(%rip), %rsi
    movq $insn_push_rax_len, %rcx
    call append_to_output

    # Load base variable -> %rax
    movq AST_OFF_NAME_PTR(%r12), %rdi
    movq AST_OFF_NAME_LEN(%r12), %rsi
    call var_find
    testq %rax, %rax
    jz .L_cs_done
    pushq %rax
    movq %rax, %rdi
    call var_get_reg
    testq %rax, %rax
    jz .L_csat_stack
    addq $8, %rsp
    pushq %rax
    leaq insn_mov_only_pre(%rip), %rsi
    movq $insn_mov_only_pre_len, %rcx
    call append_to_output
    popq %rax
    call emit_reg_name
    leaq insn_imm_rax_suf(%rip), %rsi
    movq $insn_imm_rax_suf_len, %rcx
    call append_to_output
    jmp .L_csat_loaded
.L_csat_stack:
    leaq insn_mov_rbp_rax_pre(%rip), %rsi
    movq $insn_mov_rbp_rax_pre_len, %rcx
    call append_to_output
    popq %rax
    call append_decimal_u64
    leaq insn_rbp_rax_suf(%rip), %rsi
    movq $insn_rbp_rax_suf_len, %rcx
    call append_to_output
.L_csat_loaded:

    cmpq $AST_INDEX, AST_OFF_TYPE(%r14)
    je .L_cs_assign_idx

    # AST_FIELD: popq %rcx; movq %rcx, OFFSET(%rax)
    movq AST_OFF_NAME_PTR(%r14), %rdi
    movq AST_OFF_NAME_LEN(%r14), %rsi
    call find_struct_field_off
    cmpq $-1, %rax
    jne .L_cfa_ok
    cmpq $0, struct_fld_cnt(%rip)
    je .L_cfa_zero
    movq $6, chk_err_code(%rip)
    movq AST_OFF_LINE(%r12), %rax
    movq %rax, chk_err_line(%rip)
    movq $1, out_overflow(%rip)
.L_cfa_zero:
    xorq %rax, %rax
.L_cfa_ok:
    pushq %rax
    leaq insn_pop_rcx(%rip), %rsi
    movq $insn_pop_rcx_len, %rcx
    call append_to_output
    leaq insn_mov_rcx_rax_pre(%rip), %rsi
    movq $insn_mov_rcx_rax_pre_len, %rcx
    call append_to_output
    popq %rax
    call append_decimal_u64
    leaq insn_rax_suf(%rip), %rsi
    movq $insn_rax_suf_len, %rcx
    call append_to_output
    jmp .L_cs_done

.L_cs_assign_idx:
    # push base (%rax), eval index, call axiom_array_set(rdi=base, rsi=idx, rdx=val)
    leaq insn_push_rax(%rip), %rsi
    movq $insn_push_rax_len, %rcx
    call append_to_output
    movq AST_OFF_RIGHT_PTR(%r14), %rdi
    call codegen_expr
    leaq insn_arr_set(%rip), %rsi
    movq $insn_arr_set_len, %rcx
    call append_to_output
    jmp .L_cs_done

.L_cs_store_var:
    testq %rax, %rax
    jz .L_cs_done
    movq %rax, %r13
    movq %r13, %rdi
    call var_get_reg
    testq %rax, %rax
    jz .L_cssv_stack
    pushq %rax
    leaq insn_mov_rax_reg_pre(%rip), %rsi
    movq $insn_mov_rax_reg_pre_len, %rcx
    call append_to_output
    popq %rax
    call emit_reg_name
    leaq str_def_nl(%rip), %rsi
    movq $1, %rcx
    call append_to_output
    jmp .L_cs_done
.L_cssv_stack:
    leaq insn_mov_rax_rbp_pre(%rip), %rsi
    movq $insn_mov_rax_rbp_pre_len, %rcx
    call append_to_output
    movq %r13, %rax
    call append_decimal_u64
    leaq insn_rbp_suf(%rip), %rsi
    movq $insn_rbp_suf_len, %rcx
    call append_to_output
    jmp .L_cs_done

.L_cs_call:
    movq AST_OFF_NAME_PTR(%r12), %rdi
    movq AST_OFF_NAME_LEN(%r12), %rsi
    leaq kw_println_str(%rip), %rdx
    movq $7, %rcx
    call slice_eq
    movq %rax, %r13
    testq %r13, %r13
    jnz .L_cs_do_print

    movq AST_OFF_NAME_PTR(%r12), %rdi
    movq AST_OFF_NAME_LEN(%r12), %rsi
    leaq kw_print_str(%rip), %rdx
    movq $5, %rcx
    call slice_eq
    testq %rax, %rax
    jnz .L_cs_do_print

    # User function call
    movq %r12, %rdi
    call emit_user_call
    jmp .L_cs_done

.L_cs_do_print:
    movq AST_OFF_CHILD_PTR(%r12), %rdi
    testq %rdi, %rdi
    jz .L_cs_just_nl
    cmpq $AST_STRING, AST_OFF_TYPE(%rdi)
    je .L_cs_print_str

    # Check if printing a string expression (var or concat)
    pushq %rdi
    call expr_is_str
    popq %rdi
    testq %rax, %rax
    jz .L_cs_print_num
    call codegen_expr
    leaq insn_mov_rax_rdi(%rip), %rsi
    movq $insn_mov_rax_rdi_len, %rcx
    call append_to_output
    leaq insn_call_print_str(%rip), %rsi
    movq $insn_call_print_str_len, %rcx
    call append_to_output
    jmp .L_cs_just_nl

.L_cs_print_num:
    call codegen_expr
    leaq insn_mov_rax_rdi(%rip), %rsi
    movq $insn_mov_rax_rdi_len, %rcx
    call append_to_output
    leaq insn_call_print_i64(%rip), %rsi
    movq $insn_call_print_i64_len, %rcx
    call append_to_output

.L_cs_just_nl:
    testq %r13, %r13
    jz .L_cs_done
    leaq str_print_nl(%rip), %rsi
    movq $str_print_nl_len, %rcx
    call append_to_output
    jmp .L_cs_done

.L_cs_print_str:
    movq str_count(%rip), %rax
    cmpq $4096, %rax
    jge .L_cs_done
    movq AST_OFF_NAME_PTR(%rdi), %rcx
    leaq str_table_ptrs(%rip), %rdx
    movq %rcx, (%rdx, %rax, 8)
    movq AST_OFF_NAME_LEN(%rdi), %r14
    leaq str_table_lens(%rip), %rdx
    movq %r14, (%rdx, %rax, 8)
    call emit_print_string_call
    incq str_count(%rip)
    testq %r13, %r13
    jz .L_cs_done
    leaq str_print_nl(%rip), %rsi
    movq $str_print_nl_len, %rcx
    call append_to_output
    jmp .L_cs_done

.L_cs_return:
    movq AST_OFF_CHILD_PTR(%r12), %rdi
    testq %rdi, %rdi
    jz .L_cs_ret_zero
    cmpq $0, in_fn_regalloc(%rip)
    je .L_cs_ret_eval
    cmpq $AST_CALL, AST_OFF_TYPE(%rdi)
    jne .L_cs_ret_eval
    pushq %rdi
    call is_builtin_call
    popq %rdi
    testq %rax, %rax
    jnz .L_cs_ret_eval
    movq $1, tail_call_active(%rip)
    call emit_user_call
    movq $0, tail_call_active(%rip)
    jmp .L_cs_done
.L_cs_ret_eval:
    call codegen_expr
    jmp .L_cs_ret_leave
.L_cs_ret_zero:
    leaq insn_xor_rax(%rip), %rsi
    movq $insn_xor_rax_len, %rcx
    call append_to_output
.L_cs_ret_leave:
    cmpq $0, in_fn_regalloc(%rip)
    jne .L_cs_ret_fn_epilogue
    leaq insn_leave_ret(%rip), %rsi
    movq $insn_leave_ret_len, %rcx
    call append_to_output
    jmp .L_cs_done
.L_cs_ret_fn_epilogue:
    call emit_fn_epilogue
    jmp .L_cs_done

.L_cs_if:
    incq label_seq(%rip)
    movq label_seq(%rip), %r13   # unique ID
    movq AST_OFF_CHILD_PTR(%r12), %rdi
    leaq lbl_if_else(%rip), %rsi
    movq $lbl_if_else_len, %rcx
    movq %r13, %rdx
    call codegen_cond_branch

    movq AST_OFF_RIGHT_PTR(%r12), %r14   # AST_BLOCK
    movq AST_OFF_CHILD_PTR(%r14), %rdi   # then-body
    call codegen_stmt_list

    # jmp .L_if_end_ID
    leaq insn_jmp_ifend(%rip), %rsi
    movq $insn_jmp_ifend_len, %rcx
    call append_to_output
    movq %r13, %rax
    call append_decimal_u64
    leaq str_def_nl(%rip), %rsi
    movq $1, %rcx
    call append_to_output

    # .L_if_else_ID:
    leaq lbl_if_else(%rip), %rsi
    movq $lbl_if_else_len, %rcx
    call append_to_output
    movq %r13, %rax
    call append_decimal_u64
    leaq str_def_colon(%rip), %rsi
    movq $str_def_colon_len, %rcx
    call append_to_output

    movq AST_OFF_RIGHT_PTR(%r14), %rdi   # else-body
    call codegen_stmt_list

    # .L_if_end_ID:
    leaq lbl_if_end(%rip), %rsi
    movq $lbl_if_end_len, %rcx
    call append_to_output
    movq %r13, %rax
    call append_decimal_u64
    leaq str_def_colon(%rip), %rsi
    movq $str_def_colon_len, %rcx
    call append_to_output
    jmp .L_cs_done

.L_cs_while:
    incq label_seq(%rip)
    movq label_seq(%rip), %r13

    # Check if 4x unrollable: while i < N { ...; i = i + 1 }
    movq %r12, %rdi
    call while_can_unroll
    testq %rax, %rax
    jz .L_cs_while_std

    # 4x Unrolled Loop: %r14 = i_reg, %r15 = N_imm
    movq %rdx, %r14
    movq %rcx, %r15

    # .L_wh_start_ID:
    leaq lbl_wh_start(%rip), %rsi
    movq $lbl_wh_start_len, %rcx
    call append_to_output
    movq %r13, %rax
    call append_decimal_u64
    leaq str_def_colon(%rip), %rsi
    movq $str_def_colon_len, %rcx
    call append_to_output

    # cmpq $(N - 3), %i_reg; jge .L_wh_tail_ID
    leaq insn_cmp_imm_pre(%rip), %rsi
    movq $insn_cmp_imm_pre_len, %rcx
    call append_to_output
    movq %r15, %rax
    subq $3, %rax
    call append_decimal_u64
    leaq str_comma_sp(%rip), %rsi
    movq $2, %rcx
    call append_to_output
    movq %r14, %rax
    call emit_reg_name
    leaq str_def_nl(%rip), %rsi
    movq $1, %rcx
    call append_to_output

    leaq insn_jge_pre(%rip), %rsi
    movq $insn_jge_pre_len, %rcx
    call append_to_output
    leaq lbl_wh_tail(%rip), %rsi
    movq $lbl_wh_tail_len, %rcx
    call append_to_output
    movq %r13, %rax
    call append_decimal_u64
    leaq str_def_nl(%rip), %rsi
    movq $1, %rcx
    call append_to_output

    # Emit body 4 times
    movq AST_OFF_RIGHT_PTR(%r12), %rdi
    call codegen_stmt_list
    movq AST_OFF_RIGHT_PTR(%r12), %rdi
    call codegen_stmt_list
    movq AST_OFF_RIGHT_PTR(%r12), %rdi
    call codegen_stmt_list
    movq AST_OFF_RIGHT_PTR(%r12), %rdi
    call codegen_stmt_list

    # jmp .L_wh_start_ID
    leaq insn_jmp_wh(%rip), %rsi
    movq $insn_jmp_wh_len, %rcx
    call append_to_output
    movq %r13, %rax
    call append_decimal_u64
    leaq str_def_nl(%rip), %rsi
    movq $1, %rcx
    call append_to_output

    # .L_wh_tail_ID:
    leaq lbl_wh_tail(%rip), %rsi
    movq $lbl_wh_tail_len, %rcx
    call append_to_output
    movq %r13, %rax
    call append_decimal_u64
    leaq str_def_colon(%rip), %rsi
    movq $str_def_colon_len, %rcx
    call append_to_output

    # cmpq $N, %i_reg; jge .L_wh_end_ID
    leaq insn_cmp_imm_pre(%rip), %rsi
    movq $insn_cmp_imm_pre_len, %rcx
    call append_to_output
    movq %r15, %rax
    call append_decimal_u64
    leaq str_comma_sp(%rip), %rsi
    movq $2, %rcx
    call append_to_output
    movq %r14, %rax
    call emit_reg_name
    leaq str_def_nl(%rip), %rsi
    movq $1, %rcx
    call append_to_output

    leaq insn_jge_pre(%rip), %rsi
    movq $insn_jge_pre_len, %rcx
    call append_to_output
    leaq lbl_wh_end(%rip), %rsi
    movq $lbl_wh_end_len, %rcx
    call append_to_output
    movq %r13, %rax
    call append_decimal_u64
    leaq str_def_nl(%rip), %rsi
    movq $1, %rcx
    call append_to_output

    movq AST_OFF_RIGHT_PTR(%r12), %rdi
    call codegen_stmt_list

    # jmp .L_wh_tail_ID
    leaq insn_jmp_tail(%rip), %rsi
    movq $insn_jmp_tail_len, %rcx
    call append_to_output
    movq %r13, %rax
    call append_decimal_u64
    leaq str_def_nl(%rip), %rsi
    movq $1, %rcx
    call append_to_output

    # .L_wh_end_ID:
    leaq lbl_wh_end(%rip), %rsi
    movq $lbl_wh_end_len, %rcx
    call append_to_output
    movq %r13, %rax
    call append_decimal_u64
    leaq str_def_colon(%rip), %rsi
    movq $str_def_colon_len, %rcx
