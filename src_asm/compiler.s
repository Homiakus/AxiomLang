.include "src_asm/include/axiom_defs.inc"

.section .data
code_prologue:
    .ascii "# Pure x86_64 Axiom Program generated by axlc_asm\n"
    .ascii ".global _start\n"
    .ascii ".section .text\n"
    .ascii "_start:\n"
    .ascii "    pushq %rbp\n"
    .ascii "    movq %rsp, %rbp\n"
    .ascii "    subq $128, %rsp\n"
code_prologue_len = . - code_prologue

code_epilogue:
    .ascii "    # Exit gracefully\n"
    .ascii "    leave\n"
    .ascii "    movq $60, %rax\n"
    .ascii "    xorq %rdi, %rdi\n"
    .ascii "    syscall\n\n"
    .ascii "# Pure ASM Runtime\n"
    .ascii ".global axiom_print_raw\n"
    .ascii "axiom_print_raw:\n"
    .ascii "    movq $1, %rax\n"
    .ascii "    movq $1, %rdi\n"
    .ascii "    syscall\n"
    .ascii "    ret\n"
code_epilogue_len = . - code_epilogue

str_section_header:
    .ascii "\n.section .rodata\n"
str_section_header_len = . - str_section_header

.section .bss
.align 16
src_pos:           .quad 0
dest_pos:          .quad 0
str_count:         .quad 0

# String literal table
# Stores pointers and lengths of string literals found during compilation
str_table_ptrs:    .skip 1024 * 8
str_table_lens:    .skip 1024 * 8

.section .text
.global compile_axiom_source
.global append_to_output

compile_axiom_source:
    pushq %rbp
    movq %rsp, %rbp
    pushq %rbx
    pushq %r12
    pushq %r13
    pushq %r14
    pushq %r15

    # Initialize positions
    movq $0, src_pos(%rip)
    movq $0, dest_pos(%rip)
    movq $0, str_count(%rip)

    # 1. Emit code prologue
    leaq code_prologue(%rip), %rsi
    movq $code_prologue_len, %rcx
    call append_to_output

    # 2. Main parsing loop
parse_loop:
    call skip_whitespace_and_comments
    movq src_pos(%rip), %rax
    cmpq source_len(%rip), %rax
    jge emit_finish

    # Read next identifier or keyword
    call parse_statement
    jmp parse_loop

emit_finish:
    # 3. Emit code epilogue
    leaq code_epilogue(%rip), %rsi
    movq $code_epilogue_len, %rcx
    call append_to_output

    # 4. Emit .rodata strings
    leaq str_section_header(%rip), %rsi
    movq $str_section_header_len, %rcx
    call append_to_output

    call emit_string_literals

    # Save output length
    movq dest_pos(%rip), %rax
    movq %rax, out_asm_len(%rip)

    popq %r15
    popq %r14
    popq %r13
    popq %r12
    popq %rbx
    leave
    ret

# ==============================================================================
# Buffer Appender: copies %rcx bytes from (%rsi) to out_asm_buffer at dest_pos
# ==============================================================================
append_to_output:
    pushq %rdi
    pushq %rsi
    pushq %rcx
    leaq out_asm_buffer(%rip), %rdi
    addq dest_pos(%rip), %rdi
    cld
    rep movsb
    popq %rcx
    popq %rsi
    popq %rdi
    addq %rcx, dest_pos(%rip)
    ret

# ==============================================================================
# Fast whitespace and single-line comment skipper
# ==============================================================================
skip_whitespace_and_comments:
.L_ws_loop:
    movq src_pos(%rip), %rax
    cmpq source_len(%rip), %rax
    jge .L_ws_done

    leaq source_buffer(%rip), %rbx
    movb (%rbx, %rax), %cl

    # Check ' ', '\t', '\r', '\n'
    cmpb $' ', %cl
    je .L_ws_advance
    cmpb $9, %cl
    je .L_ws_advance
    cmpb $10, %cl
    je .L_ws_advance
    cmpb $13, %cl
    je .L_ws_advance

    # Check comment "//"
    cmpb $'/', %cl
    jne .L_ws_done
    movq %rax, %rdx
    incq %rdx
    cmpq source_len(%rip), %rdx
    jge .L_ws_done
    cmpb $'/', 1(%rbx, %rax)
    jne .L_ws_done

    # Skip until newline or EOF
.L_comment_loop:
    incq src_pos(%rip)
    movq src_pos(%rip), %rax
    cmpq source_len(%rip), %rax
    jge .L_ws_done
    cmpb $10, (%rbx, %rax)
    je .L_ws_advance
    jmp .L_comment_loop

.L_ws_advance:
    incq src_pos(%rip)
    jmp .L_ws_loop

.L_ws_done:
    ret

# ==============================================================================
# Statement Parser
# ==============================================================================
parse_statement:
    # Check if starts with a string quote '"'
    leaq source_buffer(%rip), %rbx
    movq src_pos(%rip), %rax
    cmpb $'"', (%rbx, %rax)
    je parse_string_literal_stmt

    # Skip identifier or token until next whitespace or delimiter
    incq src_pos(%rip)
    ret

parse_string_literal_stmt:
    # Found opening '"'
    incq src_pos(%rip)         # skip opening quote
    movq src_pos(%rip), %r12   # r12 = string start

.L_scan_str_end:
    movq src_pos(%rip), %rax
    cmpq source_len(%rip), %rax
    jge .L_str_closed

    leaq source_buffer(%rip), %rbx
    cmpb $'"', (%rbx, %rax)
    je .L_str_closed
    incq src_pos(%rip)
    jmp .L_scan_str_end

.L_str_closed:
    movq src_pos(%rip), %r13   # r13 = string end
    movq %r13, %r14
    subq %r12, %r14            # r14 = length

    # Record string in table
    movq str_count(%rip), %rax
    cmpq $1024, %rax
    jge .L_skip_record

    leaq source_buffer(%rip), %rbx
    addq %r12, %rbx
    leaq str_table_ptrs(%rip), %rdx
    movq %rbx, (%rdx, %rax, 8)
    leaq str_table_lens(%rip), %rdx
    movq %r14, (%rdx, %rax, 8)

    # Emit call to print this string in runtime
    call emit_print_string_call

    incq str_count(%rip)

.L_skip_record:
    # Skip closing quote if present
    movq src_pos(%rip), %rax
    cmpq source_len(%rip), %rax
    jge .L_str_done
    incq src_pos(%rip)

.L_str_done:
    ret

# ==============================================================================
# Emits assembly to print string literal at index (%rax)
# ==============================================================================
emit_print_string_call:
    # Push instruction bytes:
    #   leaq .LC_str_N(%rip), %rsi
    #   movq $LEN, %rdx
    #   call axiom_print_raw
    # We write formatted text directly
    pushq %rax
    leaq str_print_prefix(%rip), %rsi
    movq $str_print_prefix_len, %rcx
    call append_to_output

    popq %rax
    pushq %rax
    call append_decimal_u64

    leaq str_print_mid(%rip), %rsi
    movq $str_print_mid_len, %rcx
    call append_to_output

    movq %r14, %rax
    call append_decimal_u64

    leaq str_print_suffix(%rip), %rsi
    movq $str_print_suffix_len, %rcx
    call append_to_output

    # Print newline after string
    leaq str_print_nl(%rip), %rsi
    movq $str_print_nl_len, %rcx
    call append_to_output

    popq %rax
    ret

.section .data
str_print_prefix:
    .ascii "    leaq .LC_str_"
str_print_prefix_len = . - str_print_prefix

str_print_mid:
    .ascii "(%rip), %rsi\n    movq $"
str_print_mid_len = . - str_print_mid

str_print_suffix:
    .ascii ", %rdx\n    call axiom_print_raw\n"
str_print_suffix_len = . - str_print_suffix

str_print_nl:
    .ascii "    leaq .LC_nl(%rip), %rsi\n    movq $1, %rdx\n    call axiom_print_raw\n"
str_print_nl_len = . - str_print_nl

.LC_nl_data:
    .ascii ".LC_nl:\n    .byte 10\n"
.LC_nl_data_len = . - .LC_nl_data

.section .text
emit_string_literals:
    # Emit newline constant
    leaq .LC_nl_data(%rip), %rsi
    movq $.LC_nl_data_len, %rcx
    call append_to_output

    # Loop over all recorded strings
    xorq %r15, %r15
.L_emit_str_loop:
    cmpq str_count(%rip), %r15
    jge .L_emit_str_done

    # Emit ".LC_str_N:\n    .ascii \""
    leaq str_def_prefix(%rip), %rsi
    movq $str_def_prefix_len, %rcx
    call append_to_output

    movq %r15, %rax
    call append_decimal_u64

    leaq str_def_mid(%rip), %rsi
    movq $str_def_mid_len, %rcx
    call append_to_output

    # Copy string content
    leaq str_table_ptrs(%rip), %rax
    movq (%rax, %r15, 8), %rsi
    leaq str_table_lens(%rip), %rax
    movq (%rax, %r15, 8), %rcx
    call append_to_output

    # Emit "\"\n"
    leaq str_def_suffix(%rip), %rsi
    movq $str_def_suffix_len, %rcx
    call append_to_output

    incq %r15
    jmp .L_emit_str_loop

.L_emit_str_done:
    ret

.section .data
str_def_prefix:
    .ascii ".LC_str_"
str_def_prefix_len = . - str_def_prefix

str_def_mid:
    .ascii ":\n    .ascii \""
str_def_mid_len = . - str_def_mid

str_def_suffix:
    .ascii "\"\n"
str_def_suffix_len = . - str_def_suffix

.section .text
# Appends unsigned 64-bit integer in %rax as ASCII decimal to output buffer
append_decimal_u64:
    pushq %rbx
    pushq %rdx
    pushq %rdi
    pushq %rsi
    pushq %rcx

    subq $32, %rsp
    leaq 31(%rsp), %rsi
    movb $0, (%rsi)
    movq $0, %rcx           # digit count

    testq %rax, %rax
    jnz .L_div_loop
    decq %rsi
    movb $'0', (%rsi)
    incq %rcx
    jmp .L_write_digits

.L_div_loop:
    testq %rax, %rax
    jz .L_write_digits
    xorq %rdx, %rdx
    movq $10, %rbx
    divq %rbx
    addb $'0', %dl
    decq %rsi
    movb %dl, (%rsi)
    incq %rcx
    jmp .L_div_loop

.L_write_digits:
    call append_to_output

    addq $32, %rsp
    popq %rcx
    popq %rsi
    popq %rdi
    popq %rdx
    popq %rbx
    ret
