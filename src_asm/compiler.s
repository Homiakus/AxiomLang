    # shift stack: pop count, pop arg, push count
    popq %rax
    popq %rdi
    pushq %rax
    call codegen_expr
    leaq insn_push_rax(%rip), %rsi
    movq $insn_push_rax_len, %rcx
    call append_to_output
    jmp .L_ebm_eloop
.L_ebm_pop:
    popq %rax
    xorq %rcx, %rcx
.L_ebm_ploop:
    cmpq %r13, %rcx
    jge .L_euc_beta_call
    pushq %rcx
    leaq pop_reg_table(%rip), %rbx
    shlq $4, %rcx
    movq (%rbx, %rcx), %rsi
    movq 8(%rbx, %rcx), %rcx
    call append_to_output
    popq %rcx
    incq %rcx
    jmp .L_ebm_ploop

.L_euc_beta_call:
    leaq insn_call_ax_pre(%rip), %rsi
    movq $insn_call_ax_pre_len, %rcx
    call append_to_output
    movq 24(%r14), %rsi
    movq 32(%r14), %rcx
    call append_to_output
    leaq str_def_nl(%rip), %rsi
    movq $1, %rcx
    call append_to_output
    popq %r14
    popq %r13
    popq %r12
    leave
    ret

.L_euc_real_user:
    # Collect args onto native stack temporarily (max 6)
    xorq %r13, %r13          # arg count
    movq AST_OFF_CHILD_PTR(%r12), %rax
.L_euc_collect:
    testq %rax, %rax
    jz .L_euc_push
    cmpq $6, %r13
    jge .L_euc_push
    pushq %rax
    incq %r13
    movq AST_OFF_NEXT_PTR(%rax), %rax
    jmp .L_euc_collect

.L_euc_push:
    cmpq $1, %r13
    jne .L_euc_push_multi
    popq %rdi
    # Fast-path: single arg is reg +- small imm -> leaq (+-)imm(%reg), %rdi
    cmpq $AST_EXPR_BIN, AST_OFF_TYPE(%rdi)
    jne .L_euc_1arg_std
    movq AST_OFF_VAL(%rdi), %rax
    cmpq $TOK_PLUS, %rax
    je .L_euc_1arg_op_ok
    cmpq $TOK_MINUS, %rax
    jne .L_euc_1arg_std
.L_euc_1arg_op_ok:
    movq AST_OFF_CHILD_PTR(%rdi), %rax
    testq %rax, %rax
    jz .L_euc_1arg_std
    cmpq $AST_IDENT, AST_OFF_TYPE(%rax)
    jne .L_euc_1arg_std
    movq AST_OFF_RIGHT_PTR(%rdi), %rcx
    testq %rcx, %rcx
    jz .L_euc_1arg_std
    cmpq $AST_INT, AST_OFF_TYPE(%rcx)
    jne .L_euc_1arg_std
    cmpq $2147483647, AST_OFF_VAL(%rcx)
    ja .L_euc_1arg_std
    pushq %rdi
    movq AST_OFF_NAME_PTR(%rax), %rdi
    movq AST_OFF_NAME_LEN(%rax), %rsi
    call var_find
    testq %rax, %rax
    jz .L_euc_1arg_pop_std
    movq %rax, %rdi
    call var_get_reg
    testq %rax, %rax
    jz .L_euc_1arg_pop_std
    popq %rdi
    # %rax = reg (1..9)
    pushq %rax
    cmpq $TOK_PLUS, AST_OFF_VAL(%rdi)
    je .L_euc_leaq_pos
    leaq insn_leaq_neg_pre(%rip), %rsi
    movq $insn_leaq_neg_pre_len, %rcx
    jmp .L_euc_leaq_emit
.L_euc_leaq_pos:
    leaq insn_leaq_pre(%rip), %rsi
    movq $insn_leaq_pre_len, %rcx
.L_euc_leaq_emit:
    pushq %rdi
    call append_to_output
    popq %rdi
    movq AST_OFF_RIGHT_PTR(%rdi), %rax
    movq AST_OFF_VAL(%rax), %rax
    call append_decimal_u64
    leaq str_lparen(%rip), %rsi
    movq $1, %rcx
    call append_to_output
    popq %rax
    call emit_reg_name
    leaq str_rparen_rdi(%rip), %rsi
    movq $8, %rcx
    call append_to_output
    jmp .L_euc_call

.L_euc_1arg_pop_std:
    popq %rdi
.L_euc_1arg_std:
    call codegen_expr
    leaq insn_mov_rax_rdi(%rip), %rsi
    movq $insn_mov_rax_rdi_len, %rcx
    call append_to_output
    jmp .L_euc_call

.L_euc_push_multi:
    # Popping from native stack gives args in reverse order (argN-1 .. arg0)!
    # Evaluate each and emit `pushq %rax` in generated code
    movq %r13, %r14
.L_euc_eval_loop:
    testq %r14, %r14
    jz .L_euc_pop_regs
    popq %rdi
    call codegen_expr
    leaq insn_push_rax(%rip), %rsi
    movq $insn_push_rax_len, %rcx
    call append_to_output
    decq %r14
    jmp .L_euc_eval_loop

.L_euc_pop_regs:
    # Generated code now has arg0 on top of stack! Pop into %rdi..%r9
    xorq %r14, %r14
.L_euc_pr_loop:
    cmpq %r13, %r14
    jge .L_euc_call
    leaq pop_reg_table(%rip), %rbx
    movq %r14, %rcx
    shlq $4, %rcx
    movq (%rbx, %rcx), %rsi
    movq 8(%rbx, %rcx), %rcx
    call append_to_output
    incq %r14
    jmp .L_euc_pr_loop

.L_euc_call:
    cmpq $0, tail_call_active(%rip)
    je .L_euc_call_normal
    movq $0, tail_call_active(%rip)
    call emit_fn_epilogue_no_ret
    leaq insn_jmp_fn_pre(%rip), %rsi
    movq $insn_jmp_fn_pre_len, %rcx
    jmp .L_euc_call_emit
.L_euc_call_normal:
    leaq insn_call_fn_pre(%rip), %rsi
    movq $insn_call_fn_pre_len, %rcx
.L_euc_call_emit:
    call append_to_output
    movq AST_OFF_NAME_PTR(%r12), %rsi
    movq AST_OFF_NAME_LEN(%r12), %rcx
    call append_to_output
    leaq str_def_nl(%rip), %rsi
    movq $1, %rcx
    call append_to_output

    popq %r14
    popq %r13
    popq %r12
    leave
    ret

# ==============================================================================
# codegen_expr(node: %rdi) -> emits x86_64 leaving result in %rax
# ==============================================================================
codegen_expr:
    pushq %rbp
    movq %rsp, %rbp
    pushq %r12
    movq %rdi, %r12
    testq %r12, %r12
    jz .L_ce_zero

    movq AST_OFF_TYPE(%r12), %rax
    cmpq $AST_INT, %rax
    je .L_ce_int
    cmpq $AST_STRING, %rax
    je .L_ce_str
    cmpq $AST_IDENT, %rax
    je .L_ce_ident
    cmpq $AST_CALL, %rax
    je .L_ce_call
    cmpq $AST_ARRAY, %rax
    je .L_ce_array
    cmpq $AST_INDEX, %rax
    je .L_ce_index
    cmpq $AST_STRUCT_LIT, %rax
    je .L_ce_struct_lit
    cmpq $AST_FIELD, %rax
    je .L_ce_field
    cmpq $AST_UNARY, %rax
    je .L_ce_unary
    cmpq $AST_EXPR_BIN, %rax
    je .L_ce_bin

.L_ce_zero:
    leaq insn_xor_rax(%rip), %rsi
    movq $insn_xor_rax_len, %rcx
    call append_to_output
    popq %r12
    leave
    ret

.L_ce_call:
    movq %r12, %rdi
    call emit_user_call
    popq %r12
    leave
    ret

.L_ce_array:
    # Allocate (count + 1) * 8 bytes via axiom_rt_alloc
    movq AST_OFF_VAL(%r12), %rax
    incq %rax
    imulq $8, %rax
    pushq %rax
    leaq insn_mov_imm_rdi(%rip), %rsi
    movq $insn_mov_imm_rdi_len, %rcx
    call append_to_output
    popq %rax
    call append_decimal_u64
    leaq insn_call_rt_alloc(%rip), %rsi
    movq $insn_call_rt_alloc_len, %rcx
    call append_to_output
    # %r12_rt = %rax (save array base on stack)
    leaq insn_push_rax(%rip), %rsi
    movq $insn_push_rax_len, %rcx
    call append_to_output
    # Store length at (%rax)
    leaq insn_mov_imm_rcx(%rip), %rsi
    movq $insn_mov_imm_rcx_len, %rcx
    call append_to_output
    movq AST_OFF_VAL(%r12), %rax
    call append_decimal_u64
    leaq insn_store_arr_len(%rip), %rsi
    movq $insn_store_arr_len_len, %rcx
    call append_to_output

    # Evaluate and store each element at [base + 8 + idx*8]
    pushq %r13
    pushq %r14
    movq AST_OFF_CHILD_PTR(%r12), %r13
    movq $1, %r14            # qword offset index
.L_arr_el_loop:
    testq %r13, %r13
    jz .L_arr_el_done
    movq %r13, %rdi
    call codegen_expr
    leaq insn_arr_el_pre(%rip), %rsi
    movq $insn_arr_el_pre_len, %rcx
    call append_to_output
    movq %r14, %rax
    imulq $8, %rax
    call append_decimal_u64
    leaq insn_arr_el_suf(%rip), %rsi
    movq $insn_arr_el_suf_len, %rcx
    call append_to_output
    incq %r14
    movq AST_OFF_NEXT_PTR(%r13), %r13
    jmp .L_arr_el_loop
.L_arr_el_done:
    popq %r14
    popq %r13
    leaq insn_pop_rax(%rip), %rsi
    movq $insn_pop_rax_len, %rcx
    call append_to_output
    popq %r12
    leave
    ret

.L_ce_index:
    movq AST_OFF_CHILD_PTR(%r12), %rdi
    call codegen_expr
    leaq insn_push_rax(%rip), %rsi
    movq $insn_push_rax_len, %rcx
    call append_to_output
    movq AST_OFF_RIGHT_PTR(%r12), %rdi
    call codegen_expr
    leaq insn_arr_get(%rip), %rsi
    movq $insn_arr_get_len, %rcx
    call append_to_output
    popq %r12
    leave
    ret

.L_ce_struct_lit:
    movq AST_OFF_VAL(%r12), %rax
    testq %rax, %rax
    jnz .L_csl_alloc
    movq $1, %rax
.L_csl_alloc:
    imulq $8, %rax
    pushq %rax
    leaq insn_mov_imm_rdi(%rip), %rsi
    movq $insn_mov_imm_rdi_len, %rcx
    call append_to_output
    popq %rax
    call append_decimal_u64
    leaq insn_call_rt_alloc(%rip), %rsi
    movq $insn_call_rt_alloc_len, %rcx
    call append_to_output
    leaq insn_push_rax(%rip), %rsi
    movq $insn_push_rax_len, %rcx
    call append_to_output

    pushq %r13
    pushq %r14
    movq AST_OFF_CHILD_PTR(%r12), %r13
    xorq %r14, %r14            # fallback field idx
.L_slit_loop:
    testq %r13, %r13
    jz .L_slit_done
    movq AST_OFF_CHILD_PTR(%r13), %rdi
    call codegen_expr

    # Look up field offset or use r14*8
    movq AST_OFF_NAME_PTR(%r13), %rdi
    movq AST_OFF_NAME_LEN(%r13), %rsi
    call find_struct_field_off
    cmpq $-1, %rax
    jne .L_slit_off_ok
    movq %r14, %rax
    imulq $8, %rax
.L_slit_off_ok:
    pushq %rax
    leaq insn_arr_el_pre(%rip), %rsi
    movq $insn_arr_el_pre_len, %rcx
    call append_to_output
    popq %rax
    call append_decimal_u64
    leaq insn_arr_el_suf(%rip), %rsi
    movq $insn_arr_el_suf_len, %rcx
    call append_to_output
    incq %r14
    movq AST_OFF_NEXT_PTR(%r13), %r13
    jmp .L_slit_loop
.L_slit_done:
    popq %r14
    popq %r13
    leaq insn_pop_rax(%rip), %rsi
    movq $insn_pop_rax_len, %rcx
    call append_to_output
    popq %r12
    leave
    ret

.L_ce_field:
    movq AST_OFF_CHILD_PTR(%r12), %rdi
    call codegen_expr
    movq AST_OFF_NAME_PTR(%r12), %rdi
    movq AST_OFF_NAME_LEN(%r12), %rsi
    call find_struct_field_off
    cmpq $-1, %rax
    jne .L_cfld_ok
    cmpq $0, struct_fld_cnt(%rip)
    je .L_cfld_zero
    movq $6, chk_err_code(%rip)
    movq AST_OFF_LINE(%r12), %rax
    movq %rax, chk_err_line(%rip)
    movq $1, out_overflow(%rip)
.L_cfld_zero:
    xorq %rax, %rax
.L_cfld_ok:
    pushq %rax
    leaq insn_fld_pre(%rip), %rsi
    movq $insn_fld_pre_len, %rcx
    call append_to_output
    popq %rax
    call append_decimal_u64
    leaq insn_fld_suf(%rip), %rsi
    movq $insn_fld_suf_len, %rcx
    call append_to_output
    popq %r12
    leave
    ret

.L_ce_unary:
    movq AST_OFF_CHILD_PTR(%r12), %rdi
    call codegen_expr
    cmpq $TOK_MINUS, AST_OFF_VAL(%r12)
    je .L_cu_neg
    leaq insn_not(%rip), %rsi
    movq $insn_not_len, %rcx
    call append_to_output
    popq %r12
    leave
    ret
.L_cu_neg:
    leaq insn_neg(%rip), %rsi
    movq $insn_neg_len, %rcx
    call append_to_output
    popq %r12
    leave
    ret

.L_ce_int:
    leaq insn_mov_imm_rax(%rip), %rsi
    movq $insn_mov_imm_rax_len, %rcx
    call append_to_output
    movq AST_OFF_VAL(%r12), %rax
    call append_decimal_u64
    leaq insn_rax_nl(%rip), %rsi
    movq $insn_rax_nl_len, %rcx
    call append_to_output
    popq %r12
    leave
    ret

.L_ce_str:
    movq str_count(%rip), %rax
    cmpq $4096, %rax
    jge .L_ce_zero
    movq AST_OFF_NAME_PTR(%r12), %rcx
    leaq str_table_ptrs(%rip), %rdx
    movq %rcx, (%rdx, %rax, 8)
    movq AST_OFF_NAME_LEN(%r12), %rcx
    leaq str_table_lens(%rip), %rdx
    movq %rcx, (%rdx, %rax, 8)
    pushq %rax
    leaq insn_lea_shdr_pre(%rip), %rsi
    movq $insn_lea_shdr_pre_len, %rcx
    call append_to_output
    movq (%rsp), %rax
    call append_decimal_u64
    leaq insn_lea_shdr_suf(%rip), %rsi
    movq $insn_lea_shdr_suf_len, %rcx
    call append_to_output
    leaq insn_lea_str_rcx_pre(%rip), %rsi
    movq $insn_lea_str_rcx_pre_len, %rcx
    call append_to_output
    popq %rax
    call append_decimal_u64
    leaq insn_lea_str_rcx_suf(%rip), %rsi
    movq $insn_lea_str_rcx_suf_len, %rcx
    call append_to_output
    incq str_count(%rip)
    popq %r12
    leave
    ret

.L_ce_ident:
    movq AST_OFF_NAME_PTR(%r12), %rdi
    movq AST_OFF_NAME_LEN(%r12), %rsi
    call var_find
    testq %rax, %rax
    jz .L_ce_zero
    pushq %rax
    movq %rax, %rdi
    call var_get_reg
    testq %rax, %rax
    jz .L_cei_stack
    addq $8, %rsp
    pushq %rax
    leaq insn_mov_only_pre(%rip), %rsi
    movq $insn_mov_only_pre_len, %rcx
    call append_to_output
    popq %rax
    call emit_reg_name
    leaq insn_imm_rax_suf(%rip), %rsi
    movq $insn_imm_rax_suf_len, %rcx
    call append_to_output
    popq %r12
    leave
    ret
.L_cei_stack:
    leaq insn_mov_rbp_rax_pre(%rip), %rsi
    movq $insn_mov_rbp_rax_pre_len, %rcx
    call append_to_output
    popq %rax
    call append_decimal_u64
    leaq insn_rbp_rax_suf(%rip), %rsi
    movq $insn_rbp_rax_suf_len, %rcx
    call append_to_output
    popq %r12
    leave
    ret

.L_ce_bin:
    # Compile-time Constant Folding if both sides are AST_INT
    movq AST_OFF_CHILD_PTR(%r12), %rcx
    movq AST_OFF_RIGHT_PTR(%r12), %rdx
    testq %rcx, %rcx
    jz .L_ce_bin_dyn
    testq %rdx, %rdx
    jz .L_ce_bin_dyn
    cmpq $AST_INT, AST_OFF_TYPE(%rcx)
    jne .L_ce_bin_dyn
    cmpq $AST_INT, AST_OFF_TYPE(%rdx)
    jne .L_ce_bin_dyn

    movq AST_OFF_VAL(%rcx), %rax
    movq AST_OFF_VAL(%rdx), %rcx
    movq AST_OFF_VAL(%r12), %rdx
    cmpq $TOK_PLUS, %rdx
    je .L_cf_add
    cmpq $TOK_MINUS, %rdx
    je .L_cf_sub
    cmpq $TOK_ASTERISK, %rdx
    je .L_cf_mul
    cmpq $TOK_SLASH, %rdx
    je .L_cf_div
    jmp .L_ce_bin_dyn

.L_cf_add:
    addq %rcx, %rax
    jmp .L_cf_emit
.L_cf_sub:
    subq %rcx, %rax
    js .L_ce_bin_dyn
    jmp .L_cf_emit
.L_cf_mul:
    imulq %rcx, %rax
    jmp .L_cf_emit
.L_cf_div:
    testq %rcx, %rcx
    jz .L_ce_bin_dyn
    cqo
    idivq %rcx
.L_cf_emit:
    pushq %rax
    leaq insn_mov_imm_rax(%rip), %rsi
    movq $insn_mov_imm_rax_len, %rcx
    call append_to_output
    popq %rax
    call append_decimal_u64
    leaq insn_rax_nl(%rip), %rsi
    movq $insn_rax_nl_len, %rcx
    call append_to_output
    popq %r12
    leave
    ret

.L_ce_bin_dyn:
    # Fast-path: RHS is non-negative 32-bit AST_INT and LHS is not a string
    movq AST_OFF_RIGHT_PTR(%r12), %rcx
    testq %rcx, %rcx
    jz .L_ce_bin_stack
    cmpq $AST_INT, AST_OFF_TYPE(%rcx)
    jne .L_ce_bin_stack
    movq AST_OFF_VAL(%rcx), %rax
    cmpq $0, %rax
    jl .L_ce_bin_stack
    cmpq $2147483647, %rax
    jg .L_ce_bin_stack
    pushq %rax
    movq AST_OFF_CHILD_PTR(%r12), %rdi
    call expr_is_str
    popq %rdx
    testq %rax, %rax
    jnz .L_ce_bin_stack

    movq AST_OFF_VAL(%r12), %rax
    cmpq $TOK_PLUS, %rax
    je .L_imm_ok
    cmpq $TOK_MINUS, %rax
    je .L_imm_ok
    cmpq $TOK_ASTERISK, %rax
    je .L_imm_ok
    cmpq $TOK_EQ, %rax
    je .L_imm_ok
    cmpq $TOK_NEQ, %rax
    je .L_imm_ok
    cmpq $TOK_LT, %rax
    je .L_imm_ok
    cmpq $TOK_GT, %rax
    je .L_imm_ok
    cmpq $TOK_LE, %rax
    je .L_imm_ok
    cmpq $TOK_GE, %rax
    jne .L_ce_bin_stack

.L_imm_ok:
    # Evaluate LHS directly into %rax (no stack push/pop in target!)
    pushq %rdx
    movq AST_OFF_CHILD_PTR(%r12), %rdi
    call codegen_expr
    popq %rdx

    movq AST_OFF_VAL(%r12), %rax
    cmpq $TOK_PLUS, %rax
    je .L_imm_add
    cmpq $TOK_MINUS, %rax
    je .L_imm_sub
    cmpq $TOK_ASTERISK, %rax
    je .L_imm_mul
    # Comparison: emit cmpq $imm, %rax + setcc
    pushq %rdx
    leaq insn_cmp_imm_pre(%rip), %rsi
    movq $insn_cmp_imm_pre_len, %rcx
    call append_to_output
    popq %rax
    call append_decimal_u64
    leaq insn_imm_rax_suf(%rip), %rsi
    movq $insn_imm_rax_suf_len, %rcx
    call append_to_output

    movq AST_OFF_VAL(%r12), %rax
    cmpq $TOK_EQ, %rax
    je .L_imm_set_eq
    cmpq $TOK_NEQ, %rax
    je .L_imm_set_neq
    cmpq $TOK_LT, %rax
    je .L_imm_set_lt
    cmpq $TOK_GT, %rax
    je .L_imm_set_gt
    cmpq $TOK_LE, %rax
    je .L_imm_set_le
    leaq insn_set_ge(%rip), %rsi
    movq $insn_set_ge_len, %rcx
    call append_to_output
    jmp .L_ce_done
.L_imm_set_eq:  leaq insn_set_eq(%rip),  %rsi; movq $insn_set_eq_len,  %rcx; call append_to_output; jmp .L_ce_done
.L_imm_set_neq: leaq insn_set_neq(%rip), %rsi; movq $insn_set_neq_len, %rcx; call append_to_output; jmp .L_ce_done
.L_imm_set_lt:  leaq insn_set_lt(%rip),  %rsi; movq $insn_set_lt_len,  %rcx; call append_to_output; jmp .L_ce_done
.L_imm_set_gt:  leaq insn_set_gt(%rip),  %rsi; movq $insn_set_gt_len,  %rcx; call append_to_output; jmp .L_ce_done
.L_imm_set_le:  leaq insn_set_le(%rip),  %rsi; movq $insn_set_le_len,  %rcx; call append_to_output; jmp .L_ce_done

.L_imm_add:
    testq %rdx, %rdx
    jz .L_ce_done
    pushq %rdx
    leaq insn_add_imm_pre(%rip), %rsi
    movq $insn_add_imm_pre_len, %rcx
    call append_to_output
    popq %rax
    call append_decimal_u64
    leaq insn_imm_rax_suf(%rip), %rsi
    movq $insn_imm_rax_suf_len, %rcx
    call append_to_output
    jmp .L_ce_done

.L_imm_sub:
    testq %rdx, %rdx
    jz .L_ce_done
    pushq %rdx
    leaq insn_sub_imm_pre(%rip), %rsi
    movq $insn_sub_imm_pre_len, %rcx
    call append_to_output
    popq %rax
    call append_decimal_u64
    leaq insn_imm_rax_suf(%rip), %rsi
    movq $insn_imm_rax_suf_len, %rcx
    call append_to_output
    jmp .L_ce_done

.L_imm_mul:
    testq %rdx, %rdx
    jnz .L_imm_mul_1
    leaq insn_xor_rax(%rip), %rsi
    movq $insn_xor_rax_len, %rcx
    call append_to_output
    jmp .L_ce_done
.L_imm_mul_1:
    cmpq $1, %rdx
    je .L_ce_done
    cmpq $2, %rdx
    jne .L_imm_mul_4
    leaq insn_shl_1(%rip), %rsi
    movq $insn_shl_1_len, %rcx
    call append_to_output
    jmp .L_ce_done
.L_imm_mul_4:
    cmpq $4, %rdx
    jne .L_imm_mul_8
    leaq insn_shl_2(%rip), %rsi
    movq $insn_shl_2_len, %rcx
    call append_to_output
    jmp .L_ce_done
.L_imm_mul_8:
    cmpq $8, %rdx
    jne .L_imm_mul_gen
    leaq insn_shl_3(%rip), %rsi
    movq $insn_shl_3_len, %rcx
    call append_to_output
    jmp .L_ce_done
.L_imm_mul_gen:
    pushq %rdx
    leaq insn_imul_imm_pre(%rip), %rsi
    movq $insn_imul_imm_pre_len, %rcx
    call append_to_output
    popq %rax
    call append_decimal_u64
    leaq insn_imm_rax_suf(%rip), %rsi
    movq $insn_imm_rax_suf_len, %rcx
    call append_to_output
    jmp .L_ce_done

.L_ce_bin_stack:
    # Fast-path 2: RHS is AST_IDENT in a register (%rbx..%r15) and LHS is not a string
    movq AST_OFF_RIGHT_PTR(%r12), %rcx
    testq %rcx, %rcx
    jz .L_ce_bin_lhs_reg
    cmpq $AST_IDENT, AST_OFF_TYPE(%rcx)
    jne .L_ce_bin_lhs_reg
    movq AST_OFF_NAME_PTR(%rcx), %rdi
    movq AST_OFF_NAME_LEN(%rcx), %rsi
    call var_find
    testq %rax, %rax
    jz .L_ce_bin_lhs_reg
    movq %rax, %rdi
    call var_get_reg
    testq %rax, %rax
    jz .L_ce_bin_lhs_reg
    pushq %rax
    movq AST_OFF_CHILD_PTR(%r12), %rdi
    call expr_is_str
    popq %rdx                # %rdx = reg index 1..5
    testq %rax, %rax
    jnz .L_ce_bin_lhs_reg

    movq AST_OFF_VAL(%r12), %rax
    cmpq $TOK_PLUS, %rax
    je .L_rreg_ok
    cmpq $TOK_MINUS, %rax
    je .L_rreg_ok
    cmpq $TOK_ASTERISK, %rax
    je .L_rreg_ok
    cmpq $TOK_EQ, %rax
    je .L_rreg_ok
    cmpq $TOK_NEQ, %rax
    je .L_rreg_ok
    cmpq $TOK_LT, %rax
    je .L_rreg_ok
    cmpq $TOK_GT, %rax
    je .L_rreg_ok
    cmpq $TOK_LE, %rax
    je .L_rreg_ok
    cmpq $TOK_GE, %rax
    jne .L_ce_bin_lhs_reg

.L_rreg_ok:
    pushq %rdx
    movq AST_OFF_CHILD_PTR(%r12), %rdi
    call codegen_expr
    popq %rdx

    movq AST_OFF_VAL(%r12), %rax
    cmpq $TOK_PLUS, %rax
    je .L_rreg_add
    cmpq $TOK_MINUS, %rax
    je .L_rreg_sub
    cmpq $TOK_ASTERISK, %rax
    je .L_rreg_mul
    # Comparison: cmpq %<reg>, %rax + setcc
    pushq %rdx
    leaq insn_cmp_reg_pre(%rip), %rsi
    movq $insn_cmp_reg_pre_len, %rcx
    call append_to_output
    popq %rax
    call emit_reg_name
    leaq insn_imm_rax_suf(%rip), %rsi
    movq $insn_imm_rax_suf_len, %rcx
    call append_to_output

    movq AST_OFF_VAL(%r12), %rax
    cmpq $TOK_EQ, %rax
    je .L_imm_set_eq
    cmpq $TOK_NEQ, %rax
    je .L_imm_set_neq
    cmpq $TOK_LT, %rax
    je .L_imm_set_lt
    cmpq $TOK_GT, %rax
    je .L_imm_set_gt
    cmpq $TOK_LE, %rax
    je .L_imm_set_le
    leaq insn_set_ge(%rip), %rsi
    movq $insn_set_ge_len, %rcx
    call append_to_output
    jmp .L_ce_done

.L_rreg_add:
    pushq %rdx
    leaq insn_add_reg_pre(%rip), %rsi
    movq $insn_add_reg_pre_len, %rcx
    call append_to_output
    popq %rax
    call emit_reg_name
    leaq insn_imm_rax_suf(%rip), %rsi
    movq $insn_imm_rax_suf_len, %rcx
    call append_to_output
    jmp .L_ce_done

.L_rreg_sub:
    pushq %rdx
    leaq insn_sub_reg_pre(%rip), %rsi
    movq $insn_sub_reg_pre_len, %rcx
    call append_to_output
    popq %rax
    call emit_reg_name
    leaq insn_imm_rax_suf(%rip), %rsi
    movq $insn_imm_rax_suf_len, %rcx
    call append_to_output
    jmp .L_ce_done

.L_rreg_mul:
    pushq %rdx
    leaq insn_imul_reg_pre(%rip), %rsi
    movq $insn_imul_reg_pre_len, %rcx
    call append_to_output
    popq %rax
    call emit_reg_name
    leaq insn_imm_rax_suf(%rip), %rsi
    movq $insn_imm_rax_suf_len, %rcx
    call append_to_output
    jmp .L_ce_done

.L_ce_bin_lhs_reg:
    # Fast-path 3: Commutative TOK_PLUS where LHS is AST_IDENT in a register (%rbx..%r15)
    cmpq $TOK_PLUS, AST_OFF_VAL(%r12)
    jne .L_ce_bin_slow
    movq AST_OFF_CHILD_PTR(%r12), %rcx
    testq %rcx, %rcx
    jz .L_ce_bin_slow
    cmpq $AST_IDENT, AST_OFF_TYPE(%rcx)
    jne .L_ce_bin_slow
    movq AST_OFF_NAME_PTR(%rcx), %rdi
    movq AST_OFF_NAME_LEN(%rcx), %rsi
    call var_find
    testq %rax, %rax
    jz .L_ce_bin_slow
    movq %rax, %rdi
    call var_get_reg
    testq %rax, %rax
    jz .L_ce_bin_slow
    pushq %rax
    movq AST_OFF_CHILD_PTR(%r12), %rdi
    call expr_is_str
    popq %rdx
    testq %rax, %rax
    jnz .L_ce_bin_slow
    # Evaluate RHS into %rax, then addq %<lhs_reg>, %rax
    pushq %rdx
    movq AST_OFF_RIGHT_PTR(%r12), %rdi
    call codegen_expr
    leaq insn_add_reg_pre(%rip), %rsi
    movq $insn_add_reg_pre_len, %rcx
    call append_to_output
    popq %rax
    call emit_reg_name
    leaq insn_imm_rax_suf(%rip), %rsi
    movq $insn_imm_rax_suf_len, %rcx
    call append_to_output
    jmp .L_ce_done

.L_ce_bin_slow:
    movq AST_OFF_CHILD_PTR(%r12), %rdi
    call codegen_expr
    leaq insn_push_rax(%rip), %rsi
    movq $insn_push_rax_len, %rcx
    call append_to_output

    movq AST_OFF_RIGHT_PTR(%r12), %rdi
    call codegen_expr

    leaq insn_bin_pop(%rip), %rsi
    movq $insn_bin_pop_len, %rcx
    call append_to_output

    # Check if string binary operation (+, ==, !=)
    movq AST_OFF_CHILD_PTR(%r12), %rdi
    call expr_is_str
    testq %rax, %rax
    jz .L_ce_num_ops

    movq AST_OFF_VAL(%r12), %rax
    cmpq $TOK_PLUS, %rax
    je .L_op_str_concat
    cmpq $TOK_EQ, %rax
    je .L_op_str_eq
    cmpq $TOK_NEQ, %rax
    je .L_op_str_neq
    jmp .L_ce_num_ops

.L_op_str_concat:
    leaq insn_call_str_concat(%rip), %rsi
    movq $insn_call_str_concat_len, %rcx
    call append_to_output
    jmp .L_ce_done
.L_op_str_eq:
    leaq insn_call_str_eq(%rip), %rsi
    movq $insn_call_str_eq_len, %rcx
    call append_to_output
    jmp .L_ce_done
.L_op_str_neq:
    leaq insn_call_str_neq(%rip), %rsi
    movq $insn_call_str_neq_len, %rcx
    call append_to_output
    jmp .L_ce_done

.L_ce_num_ops:
    movq AST_OFF_VAL(%r12), %rax
    cmpq $TOK_PLUS, %rax
    je .L_op_add
    cmpq $TOK_MINUS, %rax
    je .L_op_sub
    cmpq $TOK_ASTERISK, %rax
    je .L_op_mul
    cmpq $TOK_SLASH, %rax
    je .L_op_div
    cmpq $TOK_EQ, %rax
    je .L_op_eq
    cmpq $TOK_NEQ, %rax
    je .L_op_neq
    cmpq $TOK_LT, %rax
    je .L_op_lt
    cmpq $TOK_GT, %rax
    je .L_op_gt
    cmpq $TOK_LE, %rax
    je .L_op_le
    cmpq $TOK_GE, %rax
    je .L_op_ge
    cmpq $TOK_AND, %rax
    je .L_op_and
    cmpq $TOK_OR, %rax
    je .L_op_or
    jmp .L_ce_done

.L_op_add: leaq insn_add(%rip), %rsi; movq $insn_add_len, %rcx; call append_to_output; jmp .L_ce_done
.L_op_sub: leaq insn_sub(%rip), %rsi; movq $insn_sub_len, %rcx; call append_to_output; jmp .L_ce_done
.L_op_mul: leaq insn_mul(%rip), %rsi; movq $insn_mul_len, %rcx; call append_to_output; jmp .L_ce_done
.L_op_div: leaq insn_div(%rip), %rsi; movq $insn_div_len, %rcx; call append_to_output; jmp .L_ce_done
.L_op_eq:  leaq insn_eq(%rip),  %rsi; movq $insn_eq_len,  %rcx; call append_to_output; jmp .L_ce_done
.L_op_neq: leaq insn_neq(%rip), %rsi; movq $insn_neq_len, %rcx; call append_to_output; jmp .L_ce_done
.L_op_lt:  leaq insn_lt(%rip),  %rsi; movq $insn_lt_len,  %rcx; call append_to_output; jmp .L_ce_done
.L_op_gt:  leaq insn_gt(%rip),  %rsi; movq $insn_gt_len,  %rcx; call append_to_output; jmp .L_ce_done
.L_op_le:  leaq insn_le(%rip),  %rsi; movq $insn_le_len,  %rcx; call append_to_output; jmp .L_ce_done
.L_op_ge:  leaq insn_ge(%rip),  %rsi; movq $insn_ge_len,  %rcx; call append_to_output; jmp .L_ce_done
.L_op_and: leaq insn_and(%rip), %rsi; movq $insn_and_len, %rcx; call append_to_output; jmp .L_ce_done
.L_op_or:  leaq insn_or(%rip),  %rsi; movq $insn_or_len,  %rcx; call append_to_output

.L_ce_done:
    popq %r12
    leave
    ret

