var_find:
    pushq %r12
    pushq %r13
    pushq %r14
    movq %rdi, %r12
    movq %rsi, %r13
    xorq %r14, %r14
.L_vf_loop:
    cmpq var_count(%rip), %r14
    jge .L_vf_none
    leaq var_ptrs(%rip), %rax
    movq (%rax, %r14, 8), %rdx
    leaq var_lens(%rip), %rax
    movq (%rax, %r14, 8), %rcx
    movq %r12, %rdi
    movq %r13, %rsi
    call slice_eq
    testq %rax, %rax
    jnz .L_vf_hit
    incq %r14
    jmp .L_vf_loop
.L_vf_hit:
    leaq var_offsets(%rip), %rax
    movq (%rax, %r14, 8), %rax
    popq %r14
    popq %r13
    popq %r12
    ret
.L_vf_none:
    xorq %rax, %rax
    popq %r14
    popq %r13
    popq %r12
    ret

var_get_or_alloc:
    pushq %r12
    pushq %r13
    movq %rdi, %r12
    movq %rsi, %r13
    call var_find
    testq %rax, %rax
    jnz .L_vga_ret

    movq var_count(%rip), %rcx
    cmpq $1024, %rcx
    jge .L_vga_full

    leaq var_ptrs(%rip), %rdx
    movq %r12, (%rdx, %rcx, 8)
    leaq var_lens(%rip), %rdx
    movq %r13, (%rdx, %rcx, 8)

    movq %rcx, %rax
    incq %rax
    imulq $8, %rax
    leaq var_offsets(%rip), %rdx
    movq %rax, (%rdx, %rcx, 8)
    leaq var_is_str(%rip), %rdx
    movq $0, (%rdx, %rcx, 8)
    leaq var_reg(%rip), %rdx
    movq $0, (%rdx, %rcx, 8)
    incq var_count(%rip)
.L_vga_ret:
    popq %r13
    popq %r12
    ret

var_mark_str:
    # %rdi = stack offset
    xorq %rcx, %rcx
.L_vms_loop:
    cmpq var_count(%rip), %rcx
    jge .L_vms_done
    leaq var_offsets(%rip), %rax
    cmpq %rdi, (%rax, %rcx, 8)
    jne .L_vms_next
    leaq var_is_str(%rip), %rax
    movq $1, (%rax, %rcx, 8)
    ret
.L_vms_next:
    incq %rcx
    jmp .L_vms_loop
.L_vms_done:
    ret

var_check_str:
    # %rdi = ptr, %rsi = len -> %rax (1 if string var, 0 else)
    call var_find
    testq %rax, %rax
    jz .L_vcs_no
    xorq %rcx, %rcx
.L_vcs_loop:
    cmpq var_count(%rip), %rcx
    jge .L_vcs_no
    leaq var_offsets(%rip), %rdx
    cmpq %rax, (%rdx, %rcx, 8)
    jne .L_vcs_next
    leaq var_is_str(%rip), %rdx
    movq (%rdx, %rcx, 8), %rax
    ret
.L_vcs_next:
    incq %rcx
    jmp .L_vcs_loop
.L_vcs_no:
    xorq %rax, %rax
    ret

var_alloc_reg_if_avail:
    # %rdi = stack offset
    cmpq $0, in_fn_regalloc(%rip)
    je .L_vara_done
    movq $5, %rdx
    cmpq $0, fn_is_leaf(%rip)
    je .L_vara_lim
    movq $9, %rdx
.L_vara_lim:
    cmpq %rdx, reg_alloc_cnt(%rip)
    jge .L_vara_done
    xorq %rcx, %rcx
.L_vara_loop:
    cmpq var_count(%rip), %rcx
    jge .L_vara_done
    leaq var_offsets(%rip), %rax
    cmpq %rdi, (%rax, %rcx, 8)
    jne .L_vara_next
    leaq var_reg(%rip), %rax
    cmpq $0, (%rax, %rcx, 8)
    jne .L_vara_done
    incq reg_alloc_cnt(%rip)
    movq reg_alloc_cnt(%rip), %rdx
    movq %rdx, (%rax, %rcx, 8)
    ret
.L_vara_next:
    incq %rcx
    jmp .L_vara_loop
.L_vara_done:
    ret

var_get_reg:
    # %rdi = stack offset -> %rax (0=stack, 1..5=reg)
    cmpq $0, in_fn_regalloc(%rip)
    je .L_vgr_zero
    xorq %rcx, %rcx
.L_vgr_loop:
    cmpq var_count(%rip), %rcx
    jge .L_vgr_zero
    leaq var_offsets(%rip), %rax
    cmpq %rdi, (%rax, %rcx, 8)
    jne .L_vgr_next
    leaq var_reg(%rip), %rax
    movq (%rax, %rcx, 8), %rax
    ret
.L_vgr_next:
    incq %rcx
    jmp .L_vgr_loop
.L_vgr_zero:
    xorq %rax, %rax
    ret

emit_reg_name:
    # %rax = 1..9 -> appends %rbx / %r12..%r15 / %r10 / %r11 / %r8 / %r9
    decq %rax
    cmpq $8, %rax
    ja .L_ern_done
    leaq reg_name_table(%rip), %rdx
    shlq $4, %rax
    movq (%rdx, %rax), %rsi
    movq 8(%rdx, %rax), %rcx
    jmp append_to_output
.L_ern_done:
    ret

# ==============================================================================
# fn_check_leaf(node: %rdi) -> clears fn_is_leaf if any call/array/index/struct
# ==============================================================================
fn_check_leaf:
    pushq %r12
    movq %rdi, %r12
.L_fcl_loop:
    testq %r12, %r12
    jz .L_fcl_done
    movq AST_OFF_TYPE(%r12), %rax
    cmpq $AST_CALL, %rax
    je .L_fcl_not_leaf
    cmpq $AST_ARRAY, %rax
    je .L_fcl_not_leaf
    cmpq $AST_INDEX, %rax
    je .L_fcl_not_leaf
    cmpq $AST_STRUCT_LIT, %rax
    je .L_fcl_not_leaf
    movq AST_OFF_CHILD_PTR(%r12), %rdi
    call fn_check_leaf
    cmpq $0, fn_is_leaf(%rip)
    je .L_fcl_done
    movq AST_OFF_RIGHT_PTR(%r12), %rdi
    call fn_check_leaf
    cmpq $0, fn_is_leaf(%rip)
    je .L_fcl_done
    movq AST_OFF_NEXT_PTR(%r12), %r12
    jmp .L_fcl_loop
.L_fcl_not_leaf:
    movq $0, fn_is_leaf(%rip)
.L_fcl_done:
    popq %r12
    ret

# ==============================================================================
# fn_prescan_stmts(stmt_list: %rdi)
# Pre-allocates locals in register table and detects if stack frame is needed
# ==============================================================================
fn_prescan_stmts:
    pushq %r12
    movq %rdi, %r12
.L_fps_loop:
    testq %r12, %r12
    jz .L_fps_done
    movq AST_OFF_TYPE(%r12), %rax
    cmpq $AST_LET, %rax
    je .L_fps_let
    cmpq $AST_FOR, %rax
    je .L_fps_for
    cmpq $AST_IF, %rax
    je .L_fps_if
    cmpq $AST_WHILE, %rax
    je .L_fps_while
    cmpq $AST_INTENT, %rax
    je .L_fps_child
    cmpq $AST_BLOCK, %rax
    je .L_fps_child
    jmp .L_fps_next

.L_fps_let:
    movq AST_OFF_NAME_PTR(%r12), %rdi
    movq AST_OFF_NAME_LEN(%r12), %rsi
    call var_get_or_alloc
    movq %rax, %rdi
    call var_alloc_reg_if_avail
    jmp .L_fps_next

.L_fps_for:
    movq $1, fn_needs_frame(%rip)
    movq AST_OFF_RIGHT_PTR(%r12), %rdi
    call fn_prescan_stmts
    jmp .L_fps_next

.L_fps_if:
    movq AST_OFF_RIGHT_PTR(%r12), %rax
    testq %rax, %rax
    jz .L_fps_next
    pushq %rax
    movq AST_OFF_CHILD_PTR(%rax), %rdi
    call fn_prescan_stmts
    popq %rax
    movq AST_OFF_RIGHT_PTR(%rax), %rdi
    call fn_prescan_stmts
    jmp .L_fps_next

.L_fps_while:
    movq AST_OFF_RIGHT_PTR(%r12), %rdi
    call fn_prescan_stmts
    jmp .L_fps_next

.L_fps_child:
    movq AST_OFF_CHILD_PTR(%r12), %rdi
    call fn_prescan_stmts

.L_fps_next:
    movq AST_OFF_NEXT_PTR(%r12), %r12
    jmp .L_fps_loop
.L_fps_done:
    popq %r12
    ret

# ==============================================================================
# emit_fn_prologue / emit_fn_epilogue
