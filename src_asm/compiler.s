emit_fn_prologue:
    pushq %r12
    pushq %r13
    cmpq $0, fn_needs_frame(%rip)
    je .L_efp_regs
    leaq insn_pro_frame(%rip), %rsi
    movq $insn_pro_frame_len, %rcx
    call append_to_output
.L_efp_regs:
    movq reg_alloc_cnt(%rip), %r13
    cmpq $5, %r13
    jle .L_efp_cap_ok
    movq $5, %r13
.L_efp_cap_ok:
    movq $1, %r12
.L_efp_loop:
    cmpq %r13, %r12
    jg .L_efp_sub
    leaq insn_push_pre(%rip), %rsi
    movq $insn_push_pre_len, %rcx
    call append_to_output
    movq %r12, %rax
    call emit_reg_name
    leaq str_def_nl(%rip), %rsi
    movq $1, %rcx
    call append_to_output
    incq %r12
    jmp .L_efp_loop
.L_efp_sub:
    cmpq $0, fn_needs_frame(%rip)
    je .L_efp_done
    leaq insn_sub_1024(%rip), %rsi
    movq $insn_sub_1024_len, %rcx
    call append_to_output
.L_efp_done:
    popq %r13
    popq %r12
    ret

emit_fn_epilogue:
    call emit_fn_epilogue_no_ret
    leaq insn_ret_only(%rip), %rsi
    movq $insn_ret_only_len, %rcx
    jmp append_to_output

emit_fn_epilogue_no_ret:
    pushq %r12
    pushq %r13
    movq reg_alloc_cnt(%rip), %r13
    cmpq $5, %r13
    jle .L_efe_cap_ok
    movq $5, %r13
.L_efe_cap_ok:
    cmpq $0, fn_needs_frame(%rip)
    je .L_efe_regs
    leaq insn_leaq_neg(%rip), %rsi
    movq $insn_leaq_neg_len, %rcx
    call append_to_output
    movq %r13, %rax
    shlq $3, %rax
    call append_decimal_u64
    leaq insn_rbp_rsp(%rip), %rsi
    movq $insn_rbp_rsp_len, %rcx
    call append_to_output
.L_efe_regs:
    movq %r13, %r12
.L_efe_loop:
    cmpq $1, %r12
    jl .L_efe_ret
    leaq insn_pop_pre(%rip), %rsi
    movq $insn_pop_pre_len, %rcx
    call append_to_output
    movq %r12, %rax
    call emit_reg_name
    leaq str_def_nl(%rip), %rsi
    movq $1, %rcx
    call append_to_output
    decq %r12
    jmp .L_efe_loop
